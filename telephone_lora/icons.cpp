const uint8_t* Icons::getSignalIcon(int8_t rssi) {
    if (rssi > -70)  return signal_excellent;
    if (rssi > -85)  return signal_good;
    if (rssi > -100) return signal_medium;
    if (rssi > -115) return signal_low;
    return signal_none;
}

const uint8_t* Icons::getBatteryIcon(uint8_t percent, bool charging) {
    if (charging)    return battery_charging;
    if (percent > 75) return battery_full;
    if (percent > 50) return battery_75;
    if (percent > 25) return battery_50;
    if (percent > 5)  return battery_25;
    return battery_empty;
}

const uint8_t* Icons::getCallTypeIcon(uint8_t callType) {
    switch (callType) {
        case 0: return call_incoming;
        case 1: return call_outgoing;
        case 2: return call_missed;
        default: return call_active;
    }
}

